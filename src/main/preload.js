// Ponte entre a interface e o processo principal. A interface só enxerga estas funções.
const { contextBridge, ipcRenderer } = require('electron');

const invoke = (channel) => (...args) => ipcRenderer.invoke(channel, ...args);

contextBridge.exposeInMainWorld('cartucho', {
  getConfig: invoke('config:get'),
  setConfig: invoke('config:set'),
  getLibrary: invoke('library:get'),
  sync: invoke('library:sync'),
  achievementSummary: invoke('achievements:summary'),
  gameAchievements: invoke('achievements:game'),
  getProfile: invoke('profile:get'),
  launch: invoke('game:launch'),
  openInSource: invoke('game:open-source'),
  openGameFolder: invoke('game:folder'),
  pickArt: invoke('art:pick'),
  resetArt: invoke('art:reset'),
  artUrl: invoke('art:url'),
  searchImages: invoke('artsearch:images'),
  searchAlbums: invoke('artsearch:albums'),
  albumTracks: invoke('artsearch:tracks'),
  previewTrack: invoke('artsearch:preview'),
  useImage: invoke('artsearch:use-image'),
  useTrack: invoke('artsearch:use-track'),
  searchDone: invoke('artsearch:done'),
  openMusicSite: invoke('artsearch:open-site'),
  mcPresets: invoke('prism:presets'),
  renameInstance: invoke('prism:rename'),
  getMcPreset: invoke('prism:preset-get'),
  setMcPreset: invoke('prism:preset-set'),
  modsList: invoke('mods:list'),
  modsSearch: invoke('mods:search'),
  modsInstall: invoke('mods:install'),
  modsUpdate: invoke('mods:update'),
  modsToggle: invoke('mods:toggle'),
  modsRemove: invoke('mods:remove'),
  systemStats: invoke('system:stats'),
  recommendedPreset: invoke('system:recommended-preset'),
  setMcPresetAll: invoke('prism:preset-all'),
  getFriends: invoke('friends:get'),
  playWeek: invoke('history:week'),
  openProfile: invoke('steam:profile'),
  updateStatus: invoke('update:status'),
  installUpdate: invoke('update:install'),
  checkUpdate: invoke('update:check'),
  steamDownloads: invoke('steam:downloads'),
  screenshots: invoke('screenshots:list'),
  removeScreenshot: invoke('screenshots:remove'),
  getGamePreset: invoke('steam:preset-get'),
  setGamePreset: invoke('steam:preset-set'),
  restoreGamePreset: invoke('steam:preset-restore'),
  installGame: invoke('steam:install'),
  uninstallGame: invoke('steam:uninstall'),
  openDownloads: invoke('steam:open-downloads'),
  overlayClose: invoke('overlay:close'),
  overlayNavigate: invoke('overlay:navigate'),
  closeGame: invoke('game:close'),
  scanGames: invoke('custom:scan'),
  pickGameExe: invoke('custom:pick'),
  addGame: invoke('custom:add'),
  updateGame: invoke('custom:update'),
  removeGame: invoke('custom:remove'),
  pickFile: invoke('dialog:file'),
  pickFolder: invoke('dialog:folder'),
  power: invoke('system:power'),
  readClipboard: invoke('clipboard:read'),
  sofaActivity: invoke('sofa:activity'),
  capture: invoke('capture:do'),
  captureStatus: invoke('capture:status'),
  sendAudio: (data) => ipcRenderer.send('capture:audio', data),
  sendAudioError: (msg) => ipcRenderer.send('capture:audio-error', msg),
  minimize: invoke('window:minimize'),
  releaseTop: invoke('window:release-top'),
  toggleFullscreen: invoke('window:fullscreen'),
  platform: process.platform,
  on(event, callback) {
    const listener = (_e, payload) => callback(payload);
    ipcRenderer.on(event, listener);
    return () => ipcRenderer.removeListener(event, listener);
  },
});
